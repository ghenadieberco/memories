// Social — Phase 4. D9: photo-level only for v1.
// ---------------------------------------------------------------------------

export const comments = pgTable(
  "comments",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    photoId: uuid("photo_id").references(() => photos.id, {
      onDelete: "cascade",
    }),
    userId: text("user_id")
      .notNull()
      .references(() => profiles.id, { onDelete: "cascade" }),
    body: text("body").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [index("comments_photo_id_idx").on(table.photoId)],
);

export const likes = pgTable(
  "likes",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: text("user_id")
      .notNull()
      .references(() => profiles.id, { onDelete: "cascade" }),
    photoId: uuid("photo_id").references(() => photos.id, {
      onDelete: "cascade",
    }),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    uniqueIndex("likes_user_photo_uniq").on(table.userId, table.photoId),
  ],
);

/** FR-SOC-4 / A8: people, not keyword tags. */
export const persons = pgTable("persons", {
  id: uuid("id").primaryKey().defaultRandom(),
  ownerUserId: text("owner_user_id")
    .notNull()
    .references(() => profiles.id, { onDelete: "cascade" }),
  name: text("name").notNull(),
  /** Set when the person is also an app user (enables self-removal, FR-SOC-5). */
  linkedUserId: text("linked_user_id").references(() => profiles.id),
});

export const photoTags = pgTable("photo_tags", {
  id: uuid("id").primaryKey().defaultRandom(),
  photoId: uuid("photo_id")
    .notNull()
    .references(() => photos.id, { onDelete: "cascade" }),
  personId: uuid("person_id").references(() => persons.id, {
    onDelete: "cascade",
  }),
  taggedBy: text("tagged_by")
    .notNull()
    .references(() => profiles.id),
  createdAt: timestamp("created_at", { withTimezone: true })
    .notNull()
    .defaultNow(),
});

// ---------------------------------------------------------------------------
// Global application settings (D22)
// ---------------------------------------------------------------------------

/**
 * Single-row table holding app-wide switches.
 *
 * A table rather than an env var because maintenance mode has to be flipped by
 * an admin at runtime, without a redeploy — a redeploy is exactly what you
 * can't rely on when you need to freeze the app.
 */
export const appSettings = pgTable("app_settings", {
  /** Always 'global'. The check constraint enforces the single row. */
  id: text("id").primaryKey().default("global"),
  maintenanceMode: boolean("maintenance_mode").notNull().default(false),
  updatedBy: text("updated_by").references(() => profiles.id),
  updatedAt: timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow(),
});
